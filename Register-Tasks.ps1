# 在本机注册 ClashWifiGuard 的两个「机器级」配置：
#   1) 计划任务：每 5 分钟查一次，进程不在就拉起（自愈）
#   2) 开机自启：登录后延迟 30 秒启动一次
#
# 这两样都存在 Windows 自己的地盘里（C:\Windows\System32\Tasks\ 和
# AppData\Roaming\...\Startup\），并且写死了程序的绝对路径。
# 所以换机器、或换了目录，就必须重新跑一次本脚本。
# 可以重复执行，每次都覆盖旧配置。

$ErrorActionPreference = 'Stop'
$dir   = $PSScriptRoot
$ps1   = Join-Path $dir 'ClashWifiGuard.ps1'
$watch = Join-Path $dir '看护进程.vbs'

if (-not (Test-Path -LiteralPath $ps1))   { throw "找不到主程序：$ps1" }
if (-not (Test-Path -LiteralPath $watch)) { throw "找不到看护脚本：$watch" }

Write-Host "程序目录：$dir"
Write-Host ""

# ---------- 1. 计划任务 ----------
$taskName = 'ClashWifiGuard Watchdog'
try { & schtasks /delete /tn $taskName /f 2>$null | Out-Null } catch { }

$tr = 'wscript.exe "' + $watch + '"'
$out = & schtasks /create /tn $taskName /tr $tr /sc minute /mo 5 /f 2>&1
if ($LASTEXITCODE -ne 0) { throw "创建计划任务失败：$out" }
Write-Host "[1/2] OK  计划任务已注册：$taskName（每 5 分钟检查一次）"

# ---------- 2. 登录自启 ----------
$startup  = [Environment]::GetFolderPath('Startup')
$autoPath = Join-Path $startup 'ClashWifiGuard-autostart.vbs'

$vbs = @'
' ClashWifiGuard - login autostart. Waits 30s for Clash Party, then starts hidden.
' Regenerated by Register-Tasks.ps1. Delete this file to stop autostart.

Dim sh, cmd
WScript.Sleep 30000
Set sh = CreateObject("WScript.Shell")
cmd = "powershell.exe -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File ""__PS1__"""
sh.Run cmd, 0, False
'@
$vbs = $vbs.Replace('__PS1__', $ps1)
[IO.File]::WriteAllText($autoPath, $vbs, (New-Object Text.UTF8Encoding($false)))
Write-Host "[2/2] OK  开机自启已写入：$autoPath"

Write-Host ""
Write-Host "全部完成。确认状态："
$t = Get-ScheduledTask -TaskName $taskName -ErrorAction SilentlyContinue
if ($t) {
    Write-Host ("  计划任务  {0} / 下次 {1}" -f $t.State, (Get-ScheduledTaskInfo -TaskName $taskName).NextRunTime)
} else {
    Write-Host "  计划任务  未找到（异常）"
}
Write-Host "  开机自启  $(if (Test-Path -LiteralPath $autoPath) { '已启用' } else { '未启用' })"
Write-Host ""
Write-Host "如果是新机器，顺手核对一下 ClashWifiGuard.config.json 里的 Ssid"
Write-Host "是否为本机 WiFi 名称，以及 Clash Party 的安装路径是否一致。"
